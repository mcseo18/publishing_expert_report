def _build_myth_section_md(ch_num: int, ch_id: str) -> str:
    items = CHAPTER_MYTHS.get(ch_id, [])
    lines = [
        MYTH_MARKER,
        f"## {ch_num}.7 오해와 진실: 현장·이론 핵심 오해 교정",
        "",
        f"본 절에서는 제{ch_num}장에서 다룬 핵심 원리와 관련해 영농 현장 및 학습 과정에서 가장 빈번하게 발생하는 대표적 오해 {len(items)}가지를 선별하고, 검증된 1차 근거에 기반해 과학적 사실과 현장 교정 방안을 대비하여 정리한다.",
        "",
    ]
    for idx, it in enumerate(items, 1):
        lines.extend(
            [
                f"### 오해 {ch_num}-{idx}. \"{it['title']}\"",
                "",
                f"- **오해 (Myth):** {it['myth']}",
                f"- **진실 (Fact):** {it['fact']}",
                f"- **현장 교정 포인트:** {it['action']}",
                "",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def _normalize_linked_quiz_section(ch_id: str, quiz_block: str) -> tuple[str, int]:
    """기존 '## 이해도 점검 연습문제 및 해설'을 1:1 문제↔풀이 연결 구조로 표준화한다."""
    if QUIZ_MARKER in quiz_block:
        cnt = len(re.findall(r'id="' + ch_id + r'-q\d+"', quiz_block))
        return quiz_block, cnt

    # 헤더 분리
    body = re.sub(r"(?m)^##\s*이해도 점검[^\n]*\n+", "", quiz_block, count=1).strip()
    # 불필요한 중간 대분류 라벨(**1. 객관식 문항**, **2. 심화 서술형 문항**, <br>, ---) 정리
    body = re.sub(r"(?m)^\*\*\d+\.\s*(?:객관식|심화\s*서술형|서술형)\s*문항\*\*\s*$", "", body)
    body = re.sub(r"(?m)^(?:<br\s*/?>|---+)\s*$", "", body)

    # 문제 시작 패턴으로 분리:
    # 예: **1. ...**, **문항 1.** ..., **[문제 1] ...**, **1. (객관식)** ..., ### 문제 1
    q_split_re = re.compile(
        r"(?m)^(?=(?:\*\*(?:\[문제\s*\d+\]|문항\s*\d+\.?|\d+\.\s*(?:\([^)]+\)|\[[^\]]+\])?)|###\s*문제\s*\d+))"
    )
    raw_chunks = [c.strip() for c in q_split_re.split(body) if c.strip()]

    # 만약 분리 결과가 너무 적으면 원문 보존
    if not raw_chunks:
        return quiz_block, 0

    pairs: list[tuple[str, str]] = []
    ans_split_re = re.compile(
        r"(?m)^(?=\*\*(?:\[?정답(?:\s*및\s*(?:해설|모범\s*답안))?\]?:?|\[?모범\s*답안\]?:?|해설:))"
    )

    for chunk in raw_chunks:
        m = ans_split_re.search(chunk)
        if m:
            q_part = chunk[: m.start()].strip()
            a_part = chunk[m.start() :].strip()
        else:
            q_part = chunk.strip()
            a_part = ""
        # 문제 번호 접두어 정리 (### 문제 K 로 통일)
        q_part = re.sub(
            r"^(?:\*\*(?:\[문제\s*\d+\]|문항\s*\d+\.?|\d+\.)\s*|###\s*문제\s*\d+\.?\s*)",
            "",
            q_part,
            count=1,
        ).strip()
        # 선행 고아 ** 제거 (예: **1. 질문** → **1. 제거 후 남은 끝 ** 정리)
        if q_part.count("**") % 2 == 1:
            q_part = "**" + q_part
        pairs.append((q_part, a_part))

    nav_links = " · ".join(
        f"[문제 {i}](#{ch_id}-q{i}) ↔ [풀이 {i}](#{ch_id}-a{i})" for i in range(1, len(pairs) + 1)
    )

    out_lines = [
        "## 이해도 점검 연습문제 및 해설",
        QUIZ_MARKER,
        "",
        f"> **문제 ↔ 풀이 바로 연결:** {nav_links}",
        "",
    ]

    for i, (q_txt, a_txt) in enumerate(pairs, 1):
        out_lines.append(f'<a id="{ch_id}-q{i}"></a>')
        out_lines.append(f"### 문제 {i}")
        out_lines.append("")
        out_lines.append(q_txt)
        out_lines.append("")
        if a_txt:
            out_lines.append(f'<a id="{ch_id}-a{i}"></a>')
            out_lines.append(f"#### ▶ 문제 {i} 정답 및 상세 풀이")
            out_lines.append("")
            out_lines.append(a_txt)
            out_lines.append("")
            out_lines.append(f"*[↑ 문제 {i}로 돌아가기](#{ch_id}-q{i})*")
            out_lines.append("")

    return "\n".join(out_lines).rstrip() + "\n", len(pairs)


def process_all_chapters() -> dict[str, Any]:
    cfg = get_config()
    results = []
    total_myths = 0
    total_quizzes = 0

    for i in range(1, 17):
        cid = f"ch{i:02d}"
        p = cfg.chapters_dir / f"{cid}.mdx"
        if not p.is_file():
            continue
        text = p.read_text(encoding="utf-8")

        # 1) 기존 오해와 진실 섹션이 있으면 교체, 없으면 ## 참고문헌 바로 앞에 삽입
        myth_md = _build_myth_section_md(i, cid)
        if MYTH_MARKER in text:
            text = re.sub(
                rf"(?m){re.escape(MYTH_MARKER)}[\s\S]*?(?=^##\s*참고문헌|\Z)",
                myth_md + "\n",
                text,
            )
        else:
            ref_m = re.search(r"(?m)^##\s*참고문헌", text)
            if ref_m:
                text = text[: ref_m.start()].rstrip() + "\n\n" + myth_md + "\n" + text[ref_m.start() :]
            else:
                text = text.rstrip() + "\n\n" + myth_md

        # 2) ## 이해도 점검 연습문제 및 해설 을 1:1 문제↔풀이 연결 구조로 표준화
        quiz_m = re.search(
            rf"(?m)^##\s*이해도 점검[\s\S]*?(?=^{re.escape(MYTH_MARKER)}|^##\s*(?:{i}\.7\s*오해와 진실|참고문헌)|\Z)",
            text,
        )
        q_cnt = 0
        if quiz_m:
            linked_quiz, q_cnt = _normalize_linked_quiz_section(cid, quiz_m.group(0))
            text = text[: quiz_m.start()] + linked_quiz + "\n" + text[quiz_m.end() :]

        text = re.sub(r"\n{3,}", "\n\n", text)
        p.write_text(text, encoding="utf-8")
        m_cnt = len(CHAPTER_MYTHS.get(cid, []))
        total_myths += m_cnt
        total_quizzes += q_cnt
        results.append({"chapter_id": cid, "myths_added": m_cnt, "linked_quiz_pairs": q_cnt})

    summary = {
        "chapters_updated": len(results),
        "total_myths_added": total_myths,
        "total_linked_quiz_pairs": total_quizzes,
        "chapters": results,
    }
    (cfg.reports_dir / "myths_and_quiz_report.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return summary


if __name__ == "__main__":
    print(json.dumps(process_all_chapters(), ensure_ascii=False, indent=2))
